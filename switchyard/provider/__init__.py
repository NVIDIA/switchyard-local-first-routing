"""Switchyard Local-first Routing (beta) provider profile: the loopback sidecar run by the ``switchyard`` plugin.

The sidecar serves one model per preset, ``switchyard/<preset>``, each a
Verification-Gated Routing route over a local and a cloud tier, plus
``switchyard/default`` for whichever preset is the default, and
``switchyard/only-efficient`` / ``switchyard/only-capable``, which send every
request to the local or the cloud tier. Its bearer token is generated by
``hermes switchyard setup`` and stored as ``SWITCHYARD_API_KEY``.

The plugin ships this profile and copies it to
``HERMES_HOME/plugins/model-providers/switchyard/`` each time it loads. Once the
plugin is removed, the copy undoes setup, stops registering and deletes itself.
"""

import json
import logging
import shutil
from pathlib import Path
from typing import Any

from providers import register_provider
from providers.base import ProviderProfile

# Switchyard keys turn affinity (e.g. a VGR escalation holds until the next user
# turn) on this header; without it every request is judged in isolation.
SESSION_HEADER = "x-switchyard-session-id"
# Sent by every Hermes client of this provider, auxiliary ones included, which carry no session id.
CLIENT_HEADER = "x-switchyard-client"
HERMES_CLIENT = "hermes"
PREFIX = "switchyard/"
DEFAULT_MODEL = f"{PREFIX}default"
_DEFAULT_PRESETS = ("vgr",)
# The plugin's settings.AVAILABLE_ALGORITHMS.
_OFFERED_ALGORITHMS = ("vgr",)
# The plugin's settings.PIN_MODELS; this provider loads without the plugin package.
_SINGLE_TIER_MODELS = (f"{PREFIX}only-efficient", f"{PREFIX}only-capable")
# The plugin's settings.PLUGIN_ID, LEGACY_PLUGIN_ID, PROVIDER, PREVIOUS_MODEL_KEY,
# TITLE_TIMEOUT_KEY, LOCAL_PIN_MODEL, PINNED_TASKS and THINKING_OFF.
PLUGIN_ID = "nvidia-switchyard"
LEGACY_PLUGIN_ID = "switchyard"
PROVIDER = "switchyard"
# The folders the plugin installs as: its id, or the repository's folder name when installed by hand.
_PLUGIN_DIRS = (PLUGIN_ID, "switchyard")
PREVIOUS_MODEL_KEY = "previous"
TITLE_TIMEOUT_KEY = "title_timeout"
# The plugin's sidecar.RESTORE_FILE, in HERMES_HOME/switchyard.
RESTORE_FILE = "restore.json"
LOCAL_PIN_MODEL = f"{PREFIX}only-efficient"
PINNED_TASKS = ("title_generation", "approval")
THINKING_OFF = {"reasoning_effort": "none", "chat_template_kwargs.enable_thinking": False}
# The plugin's settings.TOKEN_ENV and sidecar._STREAM_TIMEOUT_KEYS.
TOKEN_ENV = "SWITCHYARD_API_KEY"
_STREAM_TIMEOUT_KEYS = ("stale_timeout_seconds", "request_timeout_seconds")

logger = logging.getLogger(__name__)


def _plugin_settings(config: Any) -> Any:
    node = config
    for key in ("plugins", "entries", PLUGIN_ID, "settings"):
        node = node.get(key) if isinstance(node, dict) else None
    return node if isinstance(node, dict) else {}


def _plugin_is_off(config: Any) -> bool:
    """Disabled, left out of the opt-in list, or no longer installed. Hermes runs no plugin code
    when a plugin is disabled or removed, so this provider profile, which still loads, notices."""
    plugins = config.get("plugins") if isinstance(config.get("plugins"), dict) else {}
    disabled, enabled = plugins.get("disabled"), plugins.get("enabled")
    if isinstance(disabled, list) and PLUGIN_ID in disabled:
        return True
    if isinstance(enabled, list) and PLUGIN_ID not in enabled:
        return True
    return _plugin_is_removed()


def _plugin_is_removed() -> bool:
    """No plugin folder holds the plugin's manifest. A folder this user cannot read, as one
    installed from an administrator shell can be, is still installed."""
    import providers
    from hermes_constants import get_hermes_home

    roots = (get_hermes_home() / "plugins", Path(providers.__file__).resolve().parent.parent / "plugins")
    for root in roots:
        for name in _PLUGIN_DIRS:
            try:
                (root / name / "plugin.yaml").stat()
            except (FileNotFoundError, NotADirectoryError):
                continue
            except OSError as error:
                logger.warning("Switchyard cannot read its plugin folder %s, so Hermes cannot load the plugin: %s. "
                               "Give this user read access to it again (on Windows, run `icacls \"%s\" /reset /t` "
                               "from an administrator terminal), then restart Hermes", root / name, error, root)
            return False
    return True


def _remove_copy() -> None:
    """Deletes the copy the plugin made of this profile, never the plugin's own, and its restore record."""
    from hermes_constants import get_hermes_home

    here = Path(__file__).resolve().parent
    if here.parent == (get_hermes_home() / "plugins" / "model-providers").resolve():
        shutil.rmtree(here, ignore_errors=True)
        (get_hermes_home() / "switchyard" / RESTORE_FILE).unlink(missing_ok=True)
        logger.info("Switchyard plugin is removed; deleted its provider profile from %s", here)


def _restore_record(config: Any) -> dict:
    """What setup replaced: the plugin's settings, or the copy setup keeps in its state folder,
    which Hermes's ``plugins remove`` leaves alone when it deletes the plugin's settings."""
    from hermes_constants import get_hermes_home

    try:
        record = json.loads((get_hermes_home() / "switchyard" / RESTORE_FILE).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        record = {}
    record = record if isinstance(record, dict) else {}
    settings = _plugin_settings(config)
    return {**record, **{key: settings[key] for key in (PREVIOUS_MODEL_KEY, TITLE_TIMEOUT_KEY) if key in settings}}


def restore_previous_model() -> bool:
    """Points Hermes back at the model (and title and approval models) Switchyard setup replaced,
    once the plugin is off; otherwise every request would go to a sidecar nothing starts any more."""
    from hermes_cli.config import load_config_readonly, set_config_value, unset_config_value

    config = load_config_readonly() or {}
    if not _plugin_is_off(config):
        return False
    record = _restore_record(config)
    # Setup run while Switchyard was already the model records nothing, but still pins.
    previous = record.get(PREVIOUS_MODEL_KEY)
    previous = previous if isinstance(previous, dict) else {}
    restored = []
    model = config.get("model")
    # A main model the user chose since setup stays; the title and approval pins are the plugin's either way.
    if isinstance(model, dict) and model.get("provider") == PROVIDER:
        before = previous.get("model")
        if not isinstance(before, dict):
            # Nothing to go back to; Hermes's own default is no model, so it asks for one.
            before = dict.fromkeys(("provider", "default", "base_url"), "")
            logger.warning("Switchyard plugin is off and recorded no earlier model; pick one with `hermes model`")
        for key, value in before.items():
            set_config_value(f"model.{key}", str(value or ""))
        restored.append(before.get("default") or "none")
    for task in PINNED_TASKS:
        node = (config.get("auxiliary") or {}).get(task) or {}
        if not (isinstance(node, dict) and node.get("provider") == PROVIDER and node.get("model") == LOCAL_PIN_MODEL):
            continue
        restored.append(task)
        before = previous.get(task)
        # Setup run after the model moved off Switchyard records Switchyard's own pin; a record
        # from before approval was pinned has no entry for it.
        if not isinstance(before, dict) or before.get("provider") == PROVIDER:
            before = dict.fromkeys(("provider", "model", "base_url"), "")
        for key, value in before.items():
            set_config_value(f"auxiliary.{task}.{key}", str(value or ""))
        for leaf, value in THINKING_OFF.items():
            path, parent, current = leaf.split("."), None, node.get("extra_body")
            for key in path:
                parent, current = current, current.get(key) if isinstance(current, dict) else None
            if current != value:
                continue
            # An emptied parent such as chat_template_kwargs would still be sent.
            sole = len(path) > 1 and isinstance(parent, dict) and len(parent) == 1
            unset_config_value(f"auxiliary.{task}.extra_body.{'.'.join(path[:-1] if sole else path)}")
    # Also once the pin itself is gone, as a disable followed by a removal leaves it.
    written = record.get(TITLE_TIMEOUT_KEY)
    titles = (config.get("auxiliary") or {}).get("title_generation")
    if written is not None and isinstance(titles, dict) and titles.get("timeout") == written:
        unset_config_value("auxiliary.title_generation.timeout")
        restored.append("title timeout")
    if restored:
        logger.info("Switchyard plugin is off; restored what it replaced (%s)", ", ".join(restored))
    return bool(restored)


def stop_sidecar() -> bool:
    """Stops the sidecar once the plugin is off. Hermes then has no ``switchyard stop`` command,
    and a sidecar left running keeps serving a plugin the user turned off."""
    from hermes_cli.config import load_config_readonly
    from hermes_constants import get_hermes_home

    if not _plugin_is_off(load_config_readonly() or {}):
        return False
    try:
        record = json.loads((get_hermes_home() / "switchyard" / "sidecar.json").read_text(encoding="utf-8"))
        port = int(record["port"])
    except (OSError, ValueError, KeyError, TypeError):
        return False
    import httpx
    from agent.secret_scope import get_secret
    from hermes_cli.config import load_env

    # While providers load, the secret scope may not hold .env's values yet.
    token = (get_secret(TOKEN_ENV) or load_env().get(TOKEN_ENV) or "").strip()
    if not token:
        logger.warning("Switchyard plugin is off but %s is not set, so its sidecar on port %d keeps running", TOKEN_ENV, port)
        return False
    try:
        response = httpx.post(f"http://127.0.0.1:{port}/monitor/shutdown",
                              headers={"Authorization": f"Bearer {token}"}, timeout=2.0)
    except httpx.ConnectError:  # not running any more; its record is stale
        return False
    except httpx.HTTPError as error:
        logger.warning("Switchyard plugin is off but could not stop its sidecar on port %d: %s", port, error)
        return False
    if response.is_error:
        logger.warning("Switchyard plugin is off but its sidecar on port %d refused to stop (HTTP %d)",
                       port, response.status_code)
        return False
    logger.info("Switchyard plugin is off; stopped its sidecar")
    return True


def remove_provider_timeouts() -> bool:
    """Takes out the stream timeouts setup wrote for the Switchyard provider once the plugin is removed."""
    from hermes_cli.config import load_config_readonly, unset_config_value

    if not _plugin_is_removed():
        return False
    provider = ((load_config_readonly() or {}).get("providers") or {}).get(PROVIDER)
    keys = [key for key in _STREAM_TIMEOUT_KEYS if isinstance(provider, dict) and key in provider]
    for key in keys:
        unset_config_value(f"providers.{PROVIDER}.{key}")
    if keys:
        logger.info("Switchyard plugin is removed; took out its provider timeouts (%s)", ", ".join(keys))
    return bool(keys)


def forget_legacy_id() -> bool:
    """Takes the plugin's id from before its rename out of the plugin lists once the plugin is removed.
    Hermes's remove clears only the names the installed plugin goes by."""
    from hermes_cli.config import load_config, save_config

    if not _plugin_is_removed():
        return False
    config = load_config()
    plugins = config.get("plugins")
    lists = [key for key in ("enabled", "disabled")
             if isinstance(plugins, dict) and isinstance(plugins.get(key), list) and LEGACY_PLUGIN_ID in plugins[key]]
    for key in lists:
        plugins[key] = [name for name in plugins[key] if name != LEGACY_PLUGIN_ID]
    if lists:
        save_config(config)
        logger.info("Switchyard plugin is removed; took its old id out of plugins.%s", " and plugins.".join(lists))
    return bool(lists)


def _offered(body: Any) -> bool:
    """Whether a saved preset uses an algorithm the plugin offers; the plugin does not load the others."""
    algorithm = body.get("algorithm") if isinstance(body, dict) else None
    return str(algorithm or _DEFAULT_PRESETS[0]).strip().lower() in _OFFERED_ALGORITHMS


def _preset_names() -> list[str]:
    """Preset names from the plugin's settings, read directly so the picker works while the sidecar is down."""
    try:
        from hermes_cli.config import load_config_readonly

        node: Any = _plugin_settings(load_config_readonly() or {})
        presets = node.get("presets")
    except Exception:
        node, presets = {}, None
    # Stored as a list of {name, ...}; a hand-written {name: preset} mapping also works.
    if isinstance(presets, list):
        bodies = {str(p.get("name")): p for p in presets if isinstance(p, dict) and p.get("name")}
    elif isinstance(presets, dict):
        bodies = {str(name): body for name, body in presets.items()}
    else:
        bodies = {}
    names = [name for name, body in bodies.items() if _offered(body)]
    if not names:
        return list(_DEFAULT_PRESETS)
    default = node.get("default_preset") if isinstance(node, dict) else None
    return sorted(names, key=lambda name: name != default)


class SwitchyardProfile(ProviderProfile):
    def build_api_kwargs_extras(
        self, *, reasoning_config: dict | None = None, session_id: str | None = None, **context: Any
    ) -> tuple[dict[str, Any], dict[str, Any]]:
        top_level: dict[str, Any] = {}
        if session_id:
            top_level["extra_headers"] = {SESSION_HEADER: str(session_id)}
        return {}, top_level

    def fetch_models(self, *, api_key: str | None = None, base_url: str | None = None, timeout: float = 8.0) -> list[str]:
        return [*(f"{PREFIX}{name}" for name in _preset_names()), *_SINGLE_TIER_MODELS]


switchyard = SwitchyardProfile(
    name="switchyard",
    aliases=("nemo-switchyard",),
    display_name="Switchyard Local-first Routing (Beta)",
    description="Beta. Route between a local and a cloud model with Verification-Gated Routing",
    env_vars=("SWITCHYARD_API_KEY",),
    base_url="http://127.0.0.1:4110/front/v1",
    default_headers={CLIENT_HEADER: HERMES_CLIENT},
    fallback_models=(f"{PREFIX}vgr",),
    default_aux_model=DEFAULT_MODEL,
    supports_health_check=False,
)

_cleaned_up = True
for _cleanup in (restore_previous_model, stop_sidecar, remove_provider_timeouts, forget_legacy_id):
    try:
        _cleanup()
    except Exception as error:  # never block provider discovery on this
        _cleaned_up = False
        logger.warning("Switchyard could not clean up after the plugin (%s): %s", _cleanup.__name__, error)

try:
    _removed = _plugin_is_removed()
except Exception as error:
    _removed = False
    logger.warning("Switchyard could not tell whether its plugin is installed: %s", error)
if not _removed:
    register_provider(switchyard)
elif _cleaned_up:
    _remove_copy()
